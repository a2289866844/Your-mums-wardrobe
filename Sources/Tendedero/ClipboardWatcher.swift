import AppKit

/// Watches new clipboard changes only. All reads and delivery occur on the
/// main thread, and declared sensitive/private clipboard entries are skipped
/// before asking their owners to provide any content data.
@MainActor
final class ClipboardWatcher {
    static let ownCopyType = NSPasteboard.PasteboardType("io.github.a2289866844.clipline.own-copy")
    private let pasteboard: NSPasteboard
    private let onNew: (ClipboardPayload) -> Bool
    private var timer: Timer?
    private var observedCount: Int
    private var attempts = 0
    private var pendingCount: Int?

    init(pasteboard: NSPasteboard = .general, onNew: @escaping (ClipboardPayload) -> Bool) {
        self.pasteboard = pasteboard
        self.onNew = onNew
        observedCount = pasteboard.changeCount
    }

    func start() {
        stop()
        observedCount = pasteboard.changeCount
        attempts = 0
        pendingCount = nil
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    deinit { timer?.invalidate() }

    /// Internal for deterministic tests; the timer uses the same method.
    func poll() {
        let count = pasteboard.changeCount
        guard count != observedCount else { return }
        if pendingCount != count { attempts = 0; pendingCount = count }
        guard !hasPrivateMarker() else { observedCount = count; attempts = 0; return }
        let payload = readPayload()
        // A provider can replace the clipboard while a promised type is read.
        // Never deliver mixed representations from different copy operations.
        guard pasteboard.changeCount == count else { attempts = 0; return }
        guard let payload else { observedCount = count; attempts = 0; return }
        if onNew(payload) {
            observedCount = count
            attempts = 0
        } else {
            attempts += 1
            if attempts >= 3 { observedCount = count; attempts = 0 }
        }
    }

    private func hasPrivateMarker() -> Bool {
        let types = Set((pasteboard.types ?? []).map(\.rawValue)
            + (pasteboard.pasteboardItems ?? []).flatMap { $0.types.map(\.rawValue) })
        let blocked: Set<String> = [Self.ownCopyType.rawValue, "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        if !types.isDisjoint(with: blocked) { return true }
        let passwordManagers = ["com.agilebits.onepassword", "com.1password", "com.lastpass", "com.bitwarden", "com.dashlane", "org.keepassxc"]
        if types.contains(where: { type in passwordManagers.contains { type.lowercased().hasPrefix($0) } }) { return true }
        // The source marker is metadata, never the copied text itself.
        let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
        let sources = (pasteboard.pasteboardItems ?? []).compactMap { $0.string(forType: sourceType) }
            + [pasteboard.string(forType: sourceType)].compactMap { $0 }
        return sources.contains { source in passwordManagers.contains { source.lowercased().hasPrefix($0) } }
    }

    private func readPayload() -> ClipboardPayload? {
        let items = pasteboard.pasteboardItems ?? []
        let fileValues = items.compactMap { $0.string(forType: .fileURL) }
        let files = fileValues.compactMap { value -> URL? in
            guard let url = URL(string: value), url.isFileURL else { return nil }
            return url.standardizedFileURL
        }
        if !files.isEmpty {
            var unique = Set<URL>()
            return .files(files.filter { unique.insert($0).inserted })
        }
        // If a file copy is present but malformed, do not mistake its icon
        // representation for an explicitly copied screenshot.
        if (pasteboard.types ?? []).contains(.fileURL) || items.contains(where: { $0.types.contains(.fileURL) }) { return nil }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), data.count <= ClipboardStore.imageDataLimit,
               let png = ClipboardStore.normalizedPNG(data) { return .image(png) }
        }
        let text = pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL)
        guard let text, !text.isEmpty, text.utf8.count <= ClipboardStore.textLimit else { return nil }
        if let url = ClipboardStore.link(in: text) { return .link(url) }
        return .text(text)
    }
}
