import Foundation
import Security

/// 一则被抓下来的剪贴板内容的种类。
public enum ItemKind: String, Codable, Sendable, CaseIterable {
    case text       // 纯文字或富文字
    case link       // 单一网址
    case image      // 图片,含截图
    case file       // 一个或多个档案路径
    case other      // 认得出型别但不属于上面任何一类
}

/// 来源判断的可信度。macOS 没有剪贴板变动通知,所以来源永远是推断出来的,
/// 这个栏位把「我有多确定」跟「我猜是谁」分开记录,避免日後的读者过度信任 sourceBundleID。
public enum Provenance: String, Codable, Sendable {
    case high       // 来自剪贴板上的来源标记或浏览器的来源网址,可信
    case medium     // 取样当下的最前景程式,而且前後 750 毫秒内没有切换过程式
    case low        // 取样当下刚好发生程式切换,可能抓错
    case unknown    // 完全判断不出来
}

/// 剪贴板上某一则内容的其中一种表示法。同一则内容常常同时有纯文字、富文字、HTML 等多种。
public struct ItemRepresentation: Codable, Sendable, Equatable {
    public let uti: String          // 统一型别识别码,例如 public.utf8-plain-text
    public let byteCount: Int
    public let blobPath: String?    // 大内容(图片)存成外部档案,这里放相对路径
    public let inlineText: String?  // 小的文字内容直接内嵌

    public init(uti: String, byteCount: Int, blobPath: String? = nil, inlineText: String? = nil) {
        self.uti = uti
        self.byteCount = byteCount
        self.blobPath = blobPath
        self.inlineText = inlineText
    }
}

/// 一则完整的剪贴板纪录。
public struct ClipItem: Codable, Sendable, Equatable {
    public var id: String                    // ULID 风格的识别码,单调递增且可排序
    public var kind: ItemKind
    public var capturedAt: Date
    public var contentHash: String           // 内容的 SHA-256,用来去重
    public var preview: String               // 面板上要显示的一行摘要
    public var searchText: String            // 要送进搜寻索引的原始文字(OCR 结果日後并入这里)
    public var sourceBundleID: String?
    public var sourceAppName: String?
    public var provenance: Provenance
    public var isPinned: Bool
    public var representations: [ItemRepresentation]

    public init(
        id: String,
        kind: ItemKind,
        capturedAt: Date,
        contentHash: String,
        preview: String,
        searchText: String,
        sourceBundleID: String? = nil,
        sourceAppName: String? = nil,
        provenance: Provenance = .unknown,
        isPinned: Bool = false,
        representations: [ItemRepresentation] = []
    ) {
        self.id = id
        self.kind = kind
        self.capturedAt = capturedAt
        self.contentHash = contentHash
        self.preview = preview
        self.searchText = searchText
        self.sourceBundleID = sourceBundleID
        self.sourceAppName = sourceAppName
        self.provenance = provenance
        self.isPinned = isPinned
        self.representations = representations
    }
}

/// 业界约定的「不要记录我」标记。密码管理器会在把密码放上剪贴板时贴上这些标记。
///
/// 重要:必须拿整块剪贴板的型别清单来比对,不能只看单一项目。
/// 有些程式把标记写成独立的一个项目,那样逐项检查会看不到它。
public enum PasteboardMarker {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    public static let source = "org.nspasteboard.source"
    public static let remoteClipboard = "com.apple.is-remote-clipboard"

    /// 出现其中任何一个就完全不记录这一则。
    public static let neverCapture: Set<String> = [
        concealed, transient, autoGenerated,
        // 几个不遵守上述约定、但有自己惯例的老程式
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.agilebits.onepassword",
    ]
}

/// 产生一个单调递增、可排序、含时间资讯的识别码。
public func makeItemID(at date: Date = Date()) -> String {
    let ms = UInt64(date.timeIntervalSince1970 * 1000)
    var random = [UInt8](repeating: 0, count: 10)
    _ = SecRandomCopyBytes(kSecRandomDefault, random.count, &random)
    let alphabet = Array("0123456789ABCDEFGHJKMNPQRSTVWXYZ")
    var out = ""
    var t = ms
    for _ in 0..<10 { out = String(alphabet[Int(t % 32)]) + out; t /= 32 }
    for b in random { out.append(alphabet[Int(b % 32)]) }
    return out
}
