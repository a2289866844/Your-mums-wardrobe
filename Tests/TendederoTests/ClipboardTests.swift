private final class ClipboardTestProvider: NSObject, NSPasteboardItemDataProvider {
    let provide: (NSPasteboard, NSPasteboardItem, NSPasteboard.PasteboardType) -> Void
    init(_ provide: @escaping (NSPasteboard, NSPasteboardItem, NSPasteboard.PasteboardType) -> Void) {
        self.provide = provide
    }
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                    provideDataForType type: NSPasteboard.PasteboardType) {
        if let pasteboard { provide(pasteboard, item, type) }
    }
}

final class ClipboardTests: XCTestCase {
    private func folder() throws -> URL {
        let url = FileManager.default.temporaryDirectory.resolvingSymlinksInPath()
            .appendingPathComponent("clipline-clipboard-test-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: url) }
        return url
    }

    private func defaults() -> UserDefaults {
        let name = "clipline-clipboard-test-\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: name)!
        defaults.set(true, forKey: "soundOff")
        addTeardownBlock { defaults.removePersistentDomain(forName: name) }
        return defaults
    }

    private func pasteboard() -> NSPasteboard {
        let pb = NSPasteboard.withUniqueName()
        addTeardownBlock { pb.releaseGlobally() }
        return pb
    }

    private func png(red: CGFloat = 0) throws -> Data {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2,
                                  bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                  isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        rep.setColor(NSColor(calibratedRed: red, green: 0, blue: 0, alpha: 1), atX: 0, y: 0)
        return try XCTUnwrap(rep.representation(using: .png, properties: [:]))
    }

    private func setText(_ text: String, on pb: NSPasteboard, marker: NSPasteboard.PasteboardType? = nil) {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if let marker { item.setString("1", forType: marker) }
        pb.clearContents()
        pb.writeObjects([item])
    }

    @MainActor
    func testWatcherBaselinesAndIgnoresSensitiveAndOwnCopies() {
        let pb = pasteboard()
        setText("already copied", on: pb)
        var texts: [String] = []
        let watcher = ClipboardWatcher(pasteboard: pb) { payload in
            if case .text(let text) = payload { texts.append(text) }
            return true
        }
        watcher.start()
        defer { watcher.stop() }
        watcher.poll()
        XCTAssertTrue(texts.isEmpty)
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword.private",
                       ClipboardWatcher.ownCopyType.rawValue] {
            setText("private content", on: pb, marker: .init(marker))
            watcher.poll()
        }
        XCTAssertTrue(texts.isEmpty)
        setText("ordinary text", on: pb)
        watcher.poll()
        watcher.poll()
        XCTAssertEqual(texts, ["ordinary text"])
    }

