import AppKit
import XCTest
@testable import Tendedero

private final class ClipboardTestProvider: NSObject, NSPasteboardItemDataProvider {
    let provide: (NSPasteboard, NSPasteboardItem, NSPasteboard.PasteboardType) -> Void
    init(_ provide: @escaping (NSPasteboard, NSPasteboardItem, NSPasteboard.PasteboardType) -> Void) {
        self.provide = provide
    }
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                    provideDataForType type: NSPasteboard.PasteboardType) {
        if let pasteboard { provide(pasteboard, item, type) }
    }
}

final class ClipboardTests: XCTestCase {
    private func folder() throws -> URL {
        let url = FileManager.default.temporaryDirectory.resolvingSymlinksInPath()
            .appendingPathComponent("clipline-clipboard-test-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: url) }
        return url
    }

    private func defaults() -> UserDefaults {
        let name = "clipline-clipboard-test-\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: name)!
        defaults.set(true, forKey: "soundOff")
        addTeardownBlock { defaults.removePersistentDomain(forName: name) }
        return defaults
    }

    private func pasteboard() -> NSPasteboard {
        let pb = NSPasteboard.withUniqueName()
        addTeardownBlock { pb.releaseGlobally() }
        return pb
    }

    private func png() throws -> Data {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2,
                                  bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                  isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        return try XCTUnwrap(rep.representation(using: .png, properties: [:]))
    }

    private func setText(_ text: String, on pb: NSPasteboard, marker: NSPasteboard.PasteboardType? = nil) {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if let marker { item.setString("1", forType: marker) }
        pb.clearContents()
        pb.writeObjects([item])
    }

    @MainActor
    func testWatcherBaselinesAndIgnoresSensitiveAndOwnCopies() {
        let pb = pasteboard()
        setText("already copied", on: pb)
        var texts: [String] = []
        let watcher = ClipboardWatcher(pasteboard: pb) { payload in
            if case .text(let text) = payload { texts.append(text) }
            return true
        }
        watcher.start()
        defer { watcher.stop() }
        watcher.poll()
        XCTAssertTrue(texts.isEmpty)
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword.private",
                       ClipboardWatcher.ownCopyType.rawValue] {
            setText("private content", on: pb, marker: .init(marker))
            watcher.poll()
        }
        XCTAssertTrue(texts.isEmpty)
        setText("ordinary text", on: pb)
        watcher.poll()
        watcher.poll()
        XCTAssertEqual(texts, ["ordinary text"])
    }

    @MainActor
    func testDeclaredPrivatePayloadIsNotRequestedFromProvider() {
        let pb = pasteboard()
        var reads = 0
        var deliveries = 0
        let watcher = ClipboardWatcher(pasteboard: pb) { _ in deliveries += 1; return true }
        let provider = ClipboardTestProvider { _, item, type in
            reads += 1
            item.setString("private", forType: type)
        }
        let item = NSPasteboardItem()
        item.setDataProvider(provider, forTypes: [.string])
        item.setString("1", forType: .init("org.nspasteboard.ConcealedType"))
        pb.clearContents()
        pb.writeObjects([item])
        watcher.poll()
        XCTAssertEqual(reads, 0)
        XCTAssertEqual(deliveries, 0)
    }

    @MainActor
    func testReadRaceDoesNotDeliverStaleCopy() {
        let pb = pasteboard()
        var received: [String] = []
        let watcher = ClipboardWatcher(pasteboard: pb) { payload in
            if case .text(let text) = payload { received.append(text) }
            return true
        }
        let provider = ClipboardTestProvider { pasteboard, item, type in
            item.setString("stale", forType: type)
            pasteboard.clearContents()
            pasteboard.setString("replacement", forType: .string)
        }
        let item = NSPasteboardItem()
        item.setDataProvider(provider, forTypes: [.string])
        pb.clearContents()
        pb.writeObjects([item])
        watcher.poll()
        XCTAssertTrue(received.isEmpty)
        watcher.poll()
        XCTAssertEqual(received, ["replacement"])
    }

    @MainActor
    func testSourceMetadataDeclaresPasswordManager() {
        let pb = pasteboard()
        var received = 0
        let watcher = ClipboardWatcher(pasteboard: pb) { _ in received += 1; return true }
        let item = NSPasteboardItem()
        item.setString("private content", forType: .string)
        item.setString("com.1password.1password", forType: .init("org.nspasteboard.source"))
        pb.clearContents()
        pb.writeObjects([item])
        watcher.poll()
        XCTAssertEqual(received, 0)
    }

    @MainActor
    func testFilesHavePriorityOverTheirImageRepresentation() throws {
        let pb = pasteboard()
        var payloads: [ClipboardPayload] = []
        let watcher = ClipboardWatcher(pasteboard: pb) { payloads.append($0); return true }
        let file = try folder().appendingPathComponent("document.pdf")
        try Data("file".utf8).write(to: file)
        let item = NSPasteboardItem()
        item.setString(file.absoluteString, forType: .fileURL)
        item.setData(try png(), forType: .png)
        item.setString("filename", forType: .string)
        pb.clearContents()
        pb.writeObjects([item])
        watcher.poll()
        XCTAssertEqual(payloads.count, 1)
        guard case .files(let urls) = payloads[0] else { return XCTFail("Copied file icon became an image") }
        XCTAssertEqual(urls, [file])
    }

    @MainActor
    func testWatcherSupportsImagesLinksAndBoundedRetry() throws {
        let pb = pasteboard()
        var payloads: [ClipboardPayload] = []
        let watcher = ClipboardWatcher(pasteboard: pb) { payloads.append($0); return true }
        pb.clearContents()
        pb.setData(try png(), forType: .png)
        watcher.poll()
        guard case .image = payloads.first else { return XCTFail("Expected image") }
        setText("https://example.com/path", on: pb)
        watcher.poll()
        guard case .link(let url) = payloads.last else { return XCTFail("Expected link") }
        XCTAssertEqual(url.absoluteString, "https://example.com/path")
        var attempts = 0
        let rejected = ClipboardWatcher(pasteboard: pb) { _ in attempts += 1; return false }
        setText("retry", on: pb)
        for _ in 0..<10 { rejected.poll() }
        XCTAssertEqual(attempts, 3)
    }

    @MainActor
    func testManagedCardsRestoreAndDeduplicateWithoutReveal() throws {
        let root = try folder()
        let preferences = defaults()
        let line = Line(defaults: preferences, clipboardFolder: root)
        var reveals = 0
        line.onCapture = { reveals += 1 }
        XCTAssertTrue(line.ingestClipboard(.text("A first line\nMore text")))
        XCTAssertTrue(line.ingestClipboard(.link(URL(string: "https://example.com/path")!)))
        XCTAssertTrue(line.ingestClipboard(.image(try png())))
        XCTAssertTrue(line.ingestClipboard(.text("A first line\nMore text")))
        XCTAssertTrue(line.ingestClipboard(.text("https://example.com/path")))
        XCTAssertTrue(line.ingestClipboard(.image(try png())))
        XCTAssertEqual(line.liveCount, 3)
        XCTAssertEqual(reveals, 3)
        let restored = Line(defaults: preferences, clipboardFolder: root)
        XCTAssertEqual(restored.items.map(\.kind), [.text, .link, .image])
        XCTAssertEqual(restored.items[0].previewText, "A first line\nMore text")
        XCTAssertEqual(restored.items[1].linkURL?.absoluteString, "https://example.com/path")
        XCTAssertEqual(restored.items.map(\.url), line.items.map(\.url))
    }

    @MainActor
    func testCopiedImageAlreadyOnScreenshotShelfDoesNotRevealAgain() throws {
        let root = try folder()
        let file = root.appendingPathComponent("existing.png")
        let data = try png()
        try data.write(to: file)
        let line = Line(defaults: defaults(), clipboardFolder: root.appendingPathComponent("Clipboard"))
        XCTAssertNotNil(line.hang(file, quietly: true))
        var reveals = 0
        line.onCapture = { reveals += 1 }
        XCTAssertTrue(line.ingestClipboard(.image(data)))
        XCTAssertEqual(line.liveCount, 1)
        XCTAssertEqual(line.items[0].url, file)
        XCTAssertEqual(reveals, 0)
    }

    @MainActor
    func testCopiesOriginalTextAndLinkWithOwnMarker() throws {
        let pb = pasteboard()
        let line = Line(defaults: defaults(), clipboardFolder: try folder())
        XCTAssertTrue(line.ingestClipboard(.text("Full original text\nSecond line")))
        line.copy(line.items[0].id, to: pb)
        XCTAssertEqual(pb.string(forType: .string), "Full original text\nSecond line")
        XCTAssertNotNil(pb.string(forType: ClipboardWatcher.ownCopyType))
        XCTAssertTrue(line.ingestClipboard(.link(URL(string: "https://example.com/path")!)))
        line.copy(line.items[1].id, to: pb)
        XCTAssertEqual(pb.string(forType: .URL), "https://example.com/path")
        XCTAssertEqual(pb.string(forType: .string), "https://example.com/path")
        XCTAssertNil(pb.string(forType: .fileURL))
    }

    @MainActor
    func testEvictionDeletesManagedCopiesAndPreservesExternalFiles() async throws {
        let root = try folder()
        let managed = root.appendingPathComponent("Clipboard")
        let external = root.appendingPathComponent("original.txt")
        try Data("original".utf8).write(to: external)
        let line = Line(defaults: defaults(), clipboardFolder: managed)
        line.maxItems = 1
        XCTAssertTrue(line.ingestClipboard(.files([external])))
        XCTAssertEqual(line.items[0].kind, .file)
        XCTAssertTrue(line.ingestClipboard(.text("first managed copy")))
        let firstManaged = try XCTUnwrap(line.items.last?.url)
        XCTAssertTrue(line.ingestClipboard(.text("second managed copy")))
        try await Task.sleep(nanoseconds: 750_000_000)
        XCTAssertTrue(FileManager.default.fileExists(atPath: external.path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: firstManaged.path))
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: managed.path).count, 1)
        line.drop(try XCTUnwrap(line.items.last?.id), quietly: true)
        try await Task.sleep(nanoseconds: 750_000_000)
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: managed.path).count, 0)
    }

    @MainActor
    func testNewCopyDoesNotEvictDraggedCardUntilRelease() async throws {
        let line = Line(defaults: defaults(), clipboardFolder: try folder())
        line.maxItems = 1
        XCTAssertTrue(line.ingestClipboard(.image(try png())))
        let original = try XCTUnwrap(line.items.first)
        line.draggingID = original.id
        XCTAssertTrue(line.ingestClipboard(.text("new copy while dragging")))
        try await Task.sleep(nanoseconds: 750_000_000)
        XCTAssertEqual(line.liveCount, 2)
        XCTAssertFalse(try XCTUnwrap(line.items.first { $0.id == original.id }).falling)
        XCTAssertTrue(FileManager.default.fileExists(atPath: original.url.path))
        line.draggingID = nil
        XCTAssertEqual(line.liveCount, 1)
        XCTAssertTrue(try XCTUnwrap(line.items.first { $0.id == original.id }).falling)
        XCTAssertTrue(FileManager.default.fileExists(atPath: original.url.path))
        try await Task.sleep(nanoseconds: 750_000_000)
        XCTAssertFalse(FileManager.default.fileExists(atPath: original.url.path))
        XCTAssertEqual(line.items.count, 1)
        XCTAssertEqual(line.items[0].previewText, "new copy while dragging")
    }

    @MainActor
    func testPressedCardSurvivesRepeatedCopiesAndReleasesCapacity() async throws {
        let line = Line(defaults: defaults(), clipboardFolder: try folder())
        line.maxItems = 1
        XCTAssertTrue(line.ingestClipboard(.text("pressed card")))
        let original = try XCTUnwrap(line.items.first)
        line.pressedID = original.id
        for index in 0..<3 { XCTAssertTrue(line.ingestClipboard(.text("new copy \(index)"))) }
        XCTAssertEqual(line.liveCount, 2)
        XCTAssertFalse(try XCTUnwrap(line.items.first { $0.id == original.id }).falling)
        line.pressedID = nil
        XCTAssertEqual(line.liveCount, 1)
        try await Task.sleep(nanoseconds: 750_000_000)
        XCTAssertEqual(line.items.count, 1)
        XCTAssertEqual(line.items[0].previewText, "new copy 2")
    }

    @MainActor
    func testDeferredCleanupWaitsForActiveURLAndFullReleaseGrace() async throws {
        let line = Line(defaults: defaults(), clipboardFolder: try folder())
        XCTAssertTrue(line.ingestClipboard(.text("active pending removal")))
        let original = try XCTUnwrap(line.items.first)
        line.drop(original.id, quietly: true)
        line.draggingID = original.id
        try await Task.sleep(nanoseconds: 750_000_000)
        XCTAssertTrue(FileManager.default.fileExists(atPath: original.url.path))
        XCTAssertTrue(line.items.contains { $0.id == original.id })
        line.draggingID = nil
        try await Task.sleep(nanoseconds: 250_000_000)
        XCTAssertTrue(FileManager.default.fileExists(atPath: original.url.path))
        try await Task.sleep(nanoseconds: 500_000_000)
        XCTAssertFalse(FileManager.default.fileExists(atPath: original.url.path))
        XCTAssertFalse(line.items.contains { $0.id == original.id })
    }

    @MainActor
    func testRecopyDuringFallDoesNotDeleteNewCardFile() async throws {
        let line = Line(defaults: defaults(), clipboardFolder: try folder())
        XCTAssertTrue(line.ingestClipboard(.text("again")))
        let url = line.items[0].url
        line.drop(line.items[0].id, quietly: true)
        XCTAssertTrue(line.ingestClipboard(.text("again")))
        try await Task.sleep(nanoseconds: 750_000_000)
        XCTAssertEqual(line.liveCount, 1)
        XCTAssertTrue(FileManager.default.fileExists(atPath: url.path))
    }

    func testCleanupRejectsSymlinksAndUnknownFiles() throws {
        let root = try folder()
        let store = ClipboardStore(folder: root.appendingPathComponent("Clipboard"))
        let external = root.appendingPathComponent("external.txt")
        try Data("original".utf8).write(to: external)
        let (managed, _) = try store.write(Data("managed".utf8), kind: .text, extension: "txt")
        try FileManager.default.removeItem(at: managed)
        try FileManager.default.createSymbolicLink(at: managed, withDestinationURL: external)
        let unknown = store.folder.appendingPathComponent("notes.txt")
        try Data("user data".utf8).write(to: unknown)
        store.removeUnreferenced(keeping: [], minimumAge: 0)
        XCTAssertTrue(FileManager.default.fileExists(atPath: managed.path))
        XCTAssertTrue(FileManager.default.fileExists(atPath: external.path))
        XCTAssertTrue(FileManager.default.fileExists(atPath: unknown.path))
    }

    func testManagedImageFilenameCollisionDoesNotOverwriteEditedFile() throws {
        let store = ClipboardStore(folder: try folder())
        let original = try png()
        let (url, digest) = try store.write(original, kind: .image, extension: "png")
        let edited = Data("edited image contents".utf8)
        try edited.write(to: url)
        let (newURL, newDigest) = try store.write(original, kind: .image, extension: "png")
        XCTAssertNotEqual(newURL, url)
        XCTAssertEqual(newDigest, digest)
        XCTAssertEqual(try Data(contentsOf: url), edited)
        XCTAssertEqual(try Data(contentsOf: newURL), original)
        XCTAssertTrue(store.owns(newURL))
    }

    func testStartupCleanupKeepsFreshFilesButReclaimsOldOrphans() throws {
        let root = try folder()
        let store = ClipboardStore(folder: root.appendingPathComponent("Clipboard"))
        let (fresh, _) = try store.write(Data("fresh".utf8), kind: .text, extension: "txt")
        let (old, _) = try store.write(Data("old".utf8), kind: .text, extension: "txt")
        try FileManager.default.setAttributes([.modificationDate: Date().addingTimeInterval(-2 * 24 * 60 * 60)], ofItemAtPath: old.path)
        store.removeUnreferenced(keeping: [])
        XCTAssertTrue(FileManager.default.fileExists(atPath: fresh.path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: old.path))
    }

    @MainActor
    func testOversizedTextAndInvalidImagesAreRejected() throws {
        let line = Line(defaults: defaults(), clipboardFolder: try folder())
        XCTAssertFalse(line.ingestClipboard(.text(String(repeating: "a", count: ClipboardStore.textLimit + 1))))
        XCTAssertFalse(line.ingestClipboard(.image(Data("not an image".utf8))))
        XCTAssertTrue(line.items.isEmpty)
    }
}
